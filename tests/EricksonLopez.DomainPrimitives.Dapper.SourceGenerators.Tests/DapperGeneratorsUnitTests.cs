    private static string Normalize(string code) =>
        string.Join("\n", code.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None)
            .Select(l => l.TrimEnd()));

    [Fact]
    public void GenerateTypeHandler_StringPrimitive_ProducesExactCode()
    {
        var info = new PrimitiveInfo("MyCompany.Domain", "CustomerId", "string", isSmartEnum: false);
        var code = DapperTypeHandlerGenerator.GenerateTypeHandler(info);

        var expected = @"// <auto-generated/>
#nullable enable
using System;
using System.Data;
using Dapper;
using MyCompany.Domain;

namespace EricksonLopez.DomainPrimitives.Dapper.Generated;

[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
internal sealed class CustomerIdTypeHandler : SqlMapper.TypeHandler<CustomerId>
{
    public override void SetValue(IDbDataParameter parameter, CustomerId value)
    {
        parameter.Value = value.Value;
    }

    public override CustomerId Parse(object value)
    {
        if (value is null || value == DBNull.Value)
            throw new DataException($""Cannot parse null as CustomerId."");

        if (value is string s) return CustomerId.Create(s);
        return CustomerId.Create(value.ToString() ?? string.Empty);

        throw new DataException($""Cannot parse {value.GetType()} as CustomerId."");
    }
}
";
        Normalize(code).Should().Be(Normalize(expected));
    }

    [Fact]
