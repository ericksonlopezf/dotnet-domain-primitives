    [Fact]
    public void GenerateValueObjectDapperExtensions_MultiProperty_ProducesExactCode()
    {
        var props = new EquatableArray<ValueObjectProperty>(ImmutableArray.Create(
            new ValueObjectProperty("Amount", "decimal"),
            new ValueObjectProperty("Currency", "string")));

        var info = new ValueObjectInfo("MyCompany.Domain", "Money", props);
        var code = DapperValueObjectGenerator.GenerateValueObjectDapperExtensions(info);
var expected = @"// <auto-generated/>
#nullable enable
using System;
using System.Data;
using Dapper;
using MyCompany.Domain;

namespace EricksonLopez.DomainPrimitives.Dapper.Generated;

/// <summary>
/// Dapper extensions for the Money Value Object.
/// </summary>
[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
public static class MoneyDapperExtensions
{
    /// <summary>
    /// Adds the properties of the Money to the DynamicParameters.
    /// </summary>
    public static void AddParameters(this DynamicParameters parameters, Money value, string prefix = """")
    {
        parameters.Add($""{prefix}Amount"", value.Amount);
        parameters.Add($""{prefix}Currency"", value.Currency);
    }

    /// <summary>
    /// Parses a Money from an IDataRecord.
    /// </summary>
    public static Money ParseValueObject(this IDataRecord record, string prefix = """")
    {
        var idx_Amount = record.GetOrdinal($""{prefix}Amount"");
        var val_Amount = record.IsDBNull(idx_Amount) ? default : (decimal)record.GetValue(idx_Amount);
        var idx_Currency = record.GetOrdinal($""{prefix}Currency"");
        var val_Currency = record.IsDBNull(idx_Currency) ? default : (string)record.GetValue(idx_Currency);
        return Money.Create(val_Amount!, val_Currency!);
    }
}
";
        Normalize(code).Should().Be(Normalize(expected));
    }

