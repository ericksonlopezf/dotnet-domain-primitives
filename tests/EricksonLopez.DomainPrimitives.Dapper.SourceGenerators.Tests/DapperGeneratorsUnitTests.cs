    [Fact]
    public void EquatableArray_EqualityAndHashCode_Comprehensive()
    {
        var arr1 = new EquatableArray<int>(ImmutableArray.Create(1, 2, 3));
        var arr2 = new EquatableArray<int>(new[] { 1, 2, 3 });
        var arr3 = new EquatableArray<int>(ImmutableArray.Create(1, 2, 4));
        var arr4 = new EquatableArray<int>(ImmutableArray.Create(1, 2));
        var defaultArr = default(EquatableArray<int>);

        arr1.Length.Should().Be(3);
        arr1[1].Should().Be(2);
        Assert.True(arr1.Equals(arr2));
        Assert.True(arr1.Equals((object)arr2));
        Assert.False(arr1.Equals(arr3));
        Assert.False(arr1.Equals(arr4));
        Assert.False(arr1.Equals(defaultArr));
        Assert.False(arr1.Equals((object?)null));
        Assert.False(arr1.Equals((object)"not an array"));

        arr1.GetHashCode().Should().Be(arr2.GetHashCode());
        arr1.GetHashCode().Should().NotBe(arr3.GetHashCode());

        defaultArr.Length.Should().Be(0);
        defaultArr.Values.Should().BeEmpty();
    }

    [Fact]
    public void PrimitiveInfo_EqualityAndHashCode_Comprehensive()
    {
        var info1 = new PrimitiveInfo("NS", "T1", "string", isSmartEnum: false);
        var info2 = new PrimitiveInfo("NS", "T1", "string", isSmartEnum: false);
        var diffNs = new PrimitiveInfo("OtherNS", "T1", "string", isSmartEnum: false);
        var diffName = new PrimitiveInfo("NS", "T2", "string", isSmartEnum: false);
        var diffBacking = new PrimitiveInfo("NS", "T1", "int", isSmartEnum: false);
        var diffEnum = new PrimitiveInfo("NS", "T1", "string", isSmartEnum: true);

        Assert.True(info1.Equals(info2));
        Assert.True(info1.Equals((object)info2));
        Assert.False(info1.Equals(diffNs));
        Assert.False(info1.Equals(diffName));
        Assert.False(info1.Equals(diffBacking));
        Assert.False(info1.Equals(diffEnum));
        Assert.False(info1.Equals((object?)null));
        Assert.False(info1.Equals("not an info"));

        info1.GetHashCode().Should().Be(info2.GetHashCode());
        info1.GetHashCode().Should().NotBe(diffNs.GetHashCode());
        info1.GetHashCode().Should().NotBe(diffName.GetHashCode());
        info1.GetHashCode().Should().NotBe(diffBacking.GetHashCode());
        info1.GetHashCode().Should().NotBe(diffEnum.GetHashCode());
    }
