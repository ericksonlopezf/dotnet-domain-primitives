    [Fact]
    public void ValueObjectInfo_EqualityAndHashCode_Comprehensive()
    {
        var props1 = new EquatableArray<ValueObjectProperty>(ImmutableArray.Create(new ValueObjectProperty("X", "int")));
        var props2 = new EquatableArray<ValueObjectProperty>(ImmutableArray.Create(new ValueObjectProperty("X", "int")));
        var props3 = new EquatableArray<ValueObjectProperty>(ImmutableArray.Create(new ValueObjectProperty("Y", "int")));

        var info1 = new ValueObjectInfo("NS", "Vo", props1);
        var info2 = new ValueObjectInfo("NS", "Vo", props2);
        var info3 = new ValueObjectInfo("OtherNS", "Vo", props1);
        var info4 = new ValueObjectInfo("NS", "OtherVo", props1);
        var info5 = new ValueObjectInfo("NS", "Vo", props3);

        Assert.True(info1.Equals(info1));
        Assert.True(info1.Equals(info2));
        Assert.True(info1.Equals((object)info2));
        Assert.False(info1.Equals(info3));
        Assert.False(info1.Equals(info4));
        Assert.False(info1.Equals(info5));
        Assert.False(info1.Equals((object?)null));
        Assert.False(info1.Equals((ValueObjectInfo?)null));
        Assert.False(info1.Equals((object)"some string"));

        info1.GetHashCode().Should().Be(info2.GetHashCode());
        info1.GetHashCode().Should().NotBe(info3.GetHashCode());
        info1.GetHashCode().Should().NotBe(info4.GetHashCode());
        info1.GetHashCode().Should().NotBe(info5.GetHashCode());
    }

